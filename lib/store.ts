// Coding cards keep a bounded record: long command output and large diffs are trimmed to their ends.
function boundedJson(data: Record<string, unknown>) {
  const trimmed = Object.fromEntries(Object.entries(data).map(([key, value]) => [key,
    typeof value === "string" && value.length > LIMITS.codeEventText ? `[…${value.length - LIMITS.codeEventText} characters trimmed…]\n` + value.slice(-LIMITS.codeEventText) : value]));
  return JSON.stringify(trimmed);
}
export function generatedFileSummary(file: Pick<Attachment, "mimeType" | "size">) {
  return `[Generated by run_python in an earlier reply: ${file.mimeType || "file"}, ${file.size} bytes. Contents are not included; pass this name or ID in input_files to inspect it.]`;
}
