    this.db.prepare("UPDATE app_chat SET draft=?,model=COALESCE(?,model),thinking=COALESCE(?,thinking),updatedAt=? WHERE id=? AND userId=?").run(draft, model ?? null, thinking ?? null, Date.now(), chatId, userId);
